CREATE TABLE IF NOT EXISTS payment_links (
  id CHAR(36) PRIMARY KEY,
  token VARCHAR(80) NOT NULL UNIQUE,
  party_id CHAR(36) NOT NULL,
  created_by_user_id CHAR(36) NOT NULL,
  business_name VARCHAR(160) NOT NULL,
  description VARCHAR(300) NOT NULL,
  fixed_amount DECIMAL(15,2) NULL,
  expires_at TIMESTAMP(6) NOT NULL,
  status ENUM('ACTIVE','INACTIVE') NOT NULL DEFAULT 'ACTIVE',
  created_at TIMESTAMP(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
  updated_at TIMESTAMP(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6) ON UPDATE CURRENT_TIMESTAMP(6),
  CONSTRAINT fk_payment_link_party FOREIGN KEY (party_id) REFERENCES parties(id),
  CONSTRAINT fk_payment_link_creator FOREIGN KEY (created_by_user_id) REFERENCES users(id),
  CONSTRAINT chk_payment_link_amount CHECK (fixed_amount IS NULL OR fixed_amount > 0),
  INDEX idx_payment_link_party_created (party_id, created_at),
  INDEX idx_payment_link_status_expiry (status, expires_at)
) ENGINE=InnoDB;

CREATE TABLE IF NOT EXISTS payment_link_payments (
  id CHAR(36) PRIMARY KEY,
  payment_reference VARCHAR(50) NOT NULL UNIQUE,
  client_request_id VARCHAR(100) NOT NULL UNIQUE,
  payment_link_id CHAR(36) NOT NULL,
  party_id CHAR(36) NOT NULL,
  payer_name VARCHAR(160) NOT NULL,
  payer_mobile VARCHAR(20) NOT NULL,
  payer_email VARCHAR(254) NULL,
  amount DECIMAL(15,2) NOT NULL,
  payment_method_id CHAR(36) NOT NULL,
  payment_method_code VARCHAR(50) NOT NULL,
  status ENUM('PENDING','SUCCESS','FAILED','EXPIRED','CANCELLED') NOT NULL DEFAULT 'PENDING',
  provider_reference VARCHAR(150) NULL,
  failure_message VARCHAR(500) NULL,
  created_at TIMESTAMP(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
  updated_at TIMESTAMP(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6) ON UPDATE CURRENT_TIMESTAMP(6),
  completed_at TIMESTAMP(6) NULL,
  CONSTRAINT fk_link_payment_link FOREIGN KEY (payment_link_id) REFERENCES payment_links(id),
  CONSTRAINT fk_link_payment_party FOREIGN KEY (party_id) REFERENCES parties(id),
  CONSTRAINT fk_link_payment_method FOREIGN KEY (payment_method_id) REFERENCES payment_methods(id),
  CONSTRAINT chk_link_payment_amount CHECK (amount > 0),
  INDEX idx_link_payment_link_created (payment_link_id, created_at),
  INDEX idx_link_payment_party_status (party_id, status, created_at)
) ENGINE=InnoDB;
