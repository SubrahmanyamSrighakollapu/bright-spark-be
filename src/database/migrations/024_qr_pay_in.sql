CREATE TABLE IF NOT EXISTS qr_pay_in_accounts (
  id CHAR(36) PRIMARY KEY,
  code VARCHAR(60) NOT NULL UNIQUE,
  display_label VARCHAR(120) NOT NULL,
  bank_name VARCHAR(160) NOT NULL,
  upi_id VARCHAR(160) NOT NULL UNIQUE,
  payee_name VARCHAR(200) NOT NULL,
  min_amount DECIMAL(15,2) NOT NULL,
  max_amount DECIMAL(15,2) NOT NULL,
  pricing_description VARCHAR(300) NOT NULL,
  status ENUM('ACTIVE','INACTIVE') NOT NULL DEFAULT 'ACTIVE',
  sort_order INT NOT NULL DEFAULT 0,
  created_by CHAR(36) NOT NULL,
  updated_by CHAR(36) NOT NULL,
  created_at TIMESTAMP(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
  updated_at TIMESTAMP(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6) ON UPDATE CURRENT_TIMESTAMP(6),
  CONSTRAINT fk_qr_account_creator FOREIGN KEY (created_by) REFERENCES users(id),
  CONSTRAINT fk_qr_account_updater FOREIGN KEY (updated_by) REFERENCES users(id),
  CONSTRAINT chk_qr_account_amounts CHECK (min_amount > 0 AND max_amount >= min_amount),
  INDEX idx_qr_account_status_sort (status, sort_order)
) ENGINE=InnoDB;

CREATE TABLE IF NOT EXISTS qr_pay_in_submissions (
  id CHAR(36) PRIMARY KEY,
  submission_reference VARCHAR(50) NOT NULL UNIQUE,
  party_id CHAR(36) NOT NULL,
  submitted_by_user_id CHAR(36) NOT NULL,
  qr_account_id CHAR(36) NOT NULL,
  payer_name VARCHAR(160) NOT NULL,
  payer_mobile VARCHAR(20) NOT NULL,
  payer_email VARCHAR(254) NULL,
  amount DECIMAL(15,2) NOT NULL,
  utr VARCHAR(100) NOT NULL UNIQUE,
  receipt_storage_key VARCHAR(255) NOT NULL,
  receipt_original_filename VARCHAR(255) NOT NULL,
  receipt_mime_type VARCHAR(100) NOT NULL,
  receipt_size_bytes INT UNSIGNED NOT NULL,
  status ENUM('SUBMITTED','VERIFIED','REJECTED') NOT NULL DEFAULT 'SUBMITTED',
  created_at TIMESTAMP(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
  updated_at TIMESTAMP(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6) ON UPDATE CURRENT_TIMESTAMP(6),
  CONSTRAINT fk_qr_submission_party FOREIGN KEY (party_id) REFERENCES parties(id),
  CONSTRAINT fk_qr_submission_user FOREIGN KEY (submitted_by_user_id) REFERENCES users(id),
  CONSTRAINT fk_qr_submission_account FOREIGN KEY (qr_account_id) REFERENCES qr_pay_in_accounts(id),
  INDEX idx_qr_submission_party_created (party_id, created_at),
  INDEX idx_qr_submission_status_created (status, created_at)
) ENGINE=InnoDB;
