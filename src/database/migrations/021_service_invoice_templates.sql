CREATE TABLE IF NOT EXISTS service_invoice_templates (
  id CHAR(36) PRIMARY KEY,
  service_category_id CHAR(36) NOT NULL,
  service_product_id CHAR(36) NULL,
  product_scope_key CHAR(36) NOT NULL,
  template_name VARCHAR(160) NOT NULL,
  original_file_name VARCHAR(255) NOT NULL,
  mime_type VARCHAR(100) NOT NULL DEFAULT 'text/html',
  template_html LONGTEXT NOT NULL,
  is_active BOOLEAN NOT NULL DEFAULT TRUE,
  created_by CHAR(36) NULL,
  updated_by CHAR(36) NULL,
  created_at TIMESTAMP(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
  updated_at TIMESTAMP(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6) ON UPDATE CURRENT_TIMESTAMP(6),
  CONSTRAINT fk_invoice_template_category FOREIGN KEY (service_category_id) REFERENCES service_catalog_categories(id) ON DELETE CASCADE,
  CONSTRAINT fk_invoice_template_product FOREIGN KEY (service_product_id) REFERENCES service_catalog_products(id) ON DELETE CASCADE,
  CONSTRAINT fk_invoice_template_created_by FOREIGN KEY (created_by) REFERENCES users(id) ON DELETE SET NULL,
  CONSTRAINT fk_invoice_template_updated_by FOREIGN KEY (updated_by) REFERENCES users(id) ON DELETE SET NULL,
  UNIQUE KEY uq_invoice_template_scope (service_category_id, product_scope_key),
  INDEX idx_invoice_template_lookup (service_category_id, service_product_id, is_active)
) ENGINE=InnoDB;

CREATE TABLE IF NOT EXISTS transaction_invoices (
  id CHAR(36) PRIMARY KEY,
  invoice_number VARCHAR(60) NOT NULL UNIQUE,
  transaction_id CHAR(36) NOT NULL UNIQUE,
  template_id CHAR(36) NOT NULL,
  service_category_id CHAR(36) NOT NULL,
  service_product_id CHAR(36) NULL,
  party_id CHAR(36) NOT NULL,
  invoice_status ENUM('PENDING','ISSUED','CANCELLED') NOT NULL DEFAULT 'PENDING',
  template_snapshot JSON NOT NULL,
  invoice_data JSON NOT NULL,
  rendered_html LONGTEXT NOT NULL,
  issued_at TIMESTAMP(6) NULL,
  created_at TIMESTAMP(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
  updated_at TIMESTAMP(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6) ON UPDATE CURRENT_TIMESTAMP(6),
  CONSTRAINT fk_transaction_invoice_transaction FOREIGN KEY (transaction_id) REFERENCES transactions(id) ON DELETE CASCADE,
  CONSTRAINT fk_transaction_invoice_template FOREIGN KEY (template_id) REFERENCES service_invoice_templates(id),
  CONSTRAINT fk_transaction_invoice_category FOREIGN KEY (service_category_id) REFERENCES service_catalog_categories(id),
  CONSTRAINT fk_transaction_invoice_product FOREIGN KEY (service_product_id) REFERENCES service_catalog_products(id),
  CONSTRAINT fk_transaction_invoice_party FOREIGN KEY (party_id) REFERENCES parties(id),
  INDEX idx_transaction_invoice_party_created (party_id, created_at)
) ENGINE=InnoDB;
