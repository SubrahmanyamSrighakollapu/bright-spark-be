CREATE TABLE IF NOT EXISTS wallet_top_up_requests (
  id CHAR(36) PRIMARY KEY,
  request_reference VARCHAR(40) NOT NULL UNIQUE,
  party_id CHAR(36) NOT NULL,
  wallet_id CHAR(36) NOT NULL,
  requested_by_user_id CHAR(36) NOT NULL,
  amount DECIMAL(19,4) NOT NULL,
  payment_mode ENUM('BANK_TRANSFER','UPI','QR') NOT NULL,
  payment_reference VARCHAR(100) NOT NULL,
  remarks VARCHAR(500) NULL,
  proof_storage_key VARCHAR(255) NOT NULL,
  proof_original_filename VARCHAR(255) NOT NULL,
  proof_mime_type VARCHAR(100) NOT NULL,
  proof_size_bytes INT UNSIGNED NOT NULL,
  proof_checksum_sha256 CHAR(64) NOT NULL,
  status ENUM('PENDING','APPROVED','REJECTED') NOT NULL DEFAULT 'PENDING',
  review_remarks VARCHAR(1000) NULL,
  reviewed_by_user_id CHAR(36) NULL,
  reviewed_at DATETIME(6) NULL,
  ledger_entry_id CHAR(36) NULL,
  created_at DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
  updated_at DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6) ON UPDATE CURRENT_TIMESTAMP(6),
  CONSTRAINT chk_top_up_amount CHECK (amount >= 100),
  CONSTRAINT uq_top_up_payment_reference UNIQUE (payment_reference),
  CONSTRAINT uq_top_up_ledger_entry UNIQUE (ledger_entry_id),
  CONSTRAINT fk_top_up_party FOREIGN KEY (party_id) REFERENCES parties(id),
  CONSTRAINT fk_top_up_wallet FOREIGN KEY (wallet_id) REFERENCES wallets(id),
  CONSTRAINT fk_top_up_requester FOREIGN KEY (requested_by_user_id) REFERENCES users(id),
  CONSTRAINT fk_top_up_reviewer FOREIGN KEY (reviewed_by_user_id) REFERENCES users(id),
  CONSTRAINT fk_top_up_ledger FOREIGN KEY (ledger_entry_id) REFERENCES ledger_entries(id),
  INDEX idx_top_up_status_created (status, created_at),
  INDEX idx_top_up_party_created (party_id, created_at)
);
